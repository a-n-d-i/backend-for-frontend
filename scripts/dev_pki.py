"""
Development PKI for *.example.test (RFC 6761 reserved, never on the internet).

Creates
  conf/pki/ca.pem          CA certificate: import into your browser / OS once
  conf/pki/server.pem      server certificate for example.test, *.example.test
  conf/pki/server-key.pem  its private key
and puts certificate and key into the `ssls` section of conf/apisix.yaml.

The CA is name-constrained to example.test and its private key is never
written anywhere: once this script exits, nobody can issue another
certificate with it. Trusting ca.pem therefore cannot be abused for any other
domain. The server key is committed on purpose; it only protects a domain
that exists on your machine. Rerun this script to rotate everything (and
re-import ca.pem) before the server certificate expires.

    python scripts/dev_pki.py
"""
import datetime
import re
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

ROOT = Path(__file__).resolve().parents[1]
PKI = ROOT / "conf" / "pki"
APISIX_YAML = ROOT / "conf" / "apisix.yaml"
DOMAIN = "example.test"
BEGIN, END = "  # BEGIN dev-pki (generated by scripts/dev_pki.py)", "  # END dev-pki"


def _name(cn: str) -> x509.Name:
    return x509.Name([x509.NameAttribute(NameOID.ORGANIZATION_NAME, "tokenhandler dev"),
                      x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def main():
    now = datetime.datetime.now(datetime.timezone.utc)
    ca_key = ec.generate_private_key(ec.SECP256R1())
    ca_name = _name(f"{DOMAIN} dev CA (key discarded)")
    ca = (x509.CertificateBuilder()
          .subject_name(ca_name).issuer_name(ca_name)
          .public_key(ca_key.public_key())
          .serial_number(x509.random_serial_number())
          .not_valid_before(now - datetime.timedelta(minutes=5))
          .not_valid_after(now + datetime.timedelta(days=800))
          .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
          .add_extension(x509.KeyUsage(digital_signature=False, content_commitment=False, key_encipherment=False,
                                       data_encipherment=False, key_agreement=False, key_cert_sign=True,
                                       crl_sign=True, encipher_only=False, decipher_only=False), critical=True)
          # only example.test and its subdomains, nothing else
          .add_extension(x509.NameConstraints(permitted_subtrees=[x509.DNSName(DOMAIN)], excluded_subtrees=None),
                         critical=True)
          .add_extension(x509.SubjectKeyIdentifier.from_public_key(ca_key.public_key()), critical=False)
          .sign(ca_key, hashes.SHA256()))

    key = ec.generate_private_key(ec.SECP256R1())
    cert = (x509.CertificateBuilder()
            .subject_name(_name(f"*.{DOMAIN}")).issuer_name(ca_name)
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(now - datetime.timedelta(minutes=5))
            # browsers cap TLS server certificates at 398 days
            .not_valid_after(now + datetime.timedelta(days=397))
            .add_extension(x509.SubjectAlternativeName([x509.DNSName(DOMAIN), x509.DNSName(f"*.{DOMAIN}")]),
                           critical=False)
            .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
            .add_extension(x509.KeyUsage(digital_signature=True, content_commitment=False, key_encipherment=False,
                                         data_encipherment=False, key_agreement=False, key_cert_sign=False,
                                         crl_sign=False, encipher_only=False, decipher_only=False), critical=True)
            .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]), critical=False)
            .add_extension(x509.AuthorityKeyIdentifier.from_issuer_public_key(ca_key.public_key()), critical=False)
            .sign(ca_key, hashes.SHA256()))
    del ca_key  # never written: no more certificates can be issued

    PKI.mkdir(parents=True, exist_ok=True)
    ca_pem = ca.public_bytes(serialization.Encoding.PEM).decode()
    cert_pem = cert.public_bytes(serialization.Encoding.PEM).decode()
    key_pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                serialization.NoEncryption()).decode()
    (PKI / "ca.pem").write_text(ca_pem)
    (PKI / "server.pem").write_text(cert_pem)
    (PKI / "server-key.pem").write_text(key_pem)

    def block(pem: str) -> str:
        return "\n".join("      " + line for line in pem.strip().splitlines())

    ssls = (f"{BEGIN}\n  - id: example-test\n    snis: [\"{DOMAIN}\", \"*.{DOMAIN}\"]\n"
            f"    cert: |\n{block(cert_pem)}\n    key: |\n{block(key_pem)}\n{END}")
    text = APISIX_YAML.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"{APISIX_YAML} has no '{BEGIN.strip()}' ... '{END.strip()}' block")
    APISIX_YAML.write_text(pattern.sub(lambda _: ssls, text))
    print(f"wrote {PKI}/ca.pem, server.pem, server-key.pem (valid until {cert.not_valid_after_utc:%Y-%m-%d}) "
          f"and the ssls section of {APISIX_YAML}")


if __name__ == "__main__":
    main()
